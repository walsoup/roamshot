def save_img(img, filename):
    filepath = os.path.join(OUTPUT_DIR, filename)
    img.save(filepath, "PNG")
    print(f"Saved: {filename} ({img.width}x{img.height})")

def save_vector(img, name, dp_per_px):
    """Writes img as a vector drawable: one path per color, one rectangle per horizontal run."""
    runs = {}
    for y in range(img.height):
        x = 0
        while x < img.width:
            color = img.getpixel((x, y))
            if color[3] == 0:
                x += 1
                continue
            start = x
            while x < img.width and img.getpixel((x, y)) == color:
                x += 1
            runs.setdefault(color[:3], []).append(f"M{start},{y}h{x - start}v1h{start - x}z")

    lines = [
        '<?xml version="1.0" encoding="utf-8"?>',
        "<!-- Generated by design/tools/generate_procedural_assets.py. Do not edit by hand. -->",
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
        f'    android:width="{img.width * dp_per_px}dp"',
        f'    android:height="{img.height * dp_per_px}dp"',
        f'    android:viewportWidth="{img.width}"',
        f'    android:viewportHeight="{img.height}">',
    ]
    for (r, g, b), paths in runs.items():
        lines.append("    <path")
        lines.append(f'        android:fillColor="#{r:02X}{g:02X}{b:02X}"')
        lines.append(f'        android:pathData="{"".join(paths)}" />')
    lines.append("</vector>")

    filepath = os.path.join(VECTOR_DIR, f"{name}.xml")
    with open(filepath, "w") as f:
        f.write("\n".join(lines) + "\n")
    stale_png = os.path.join(OUTPUT_DIR, f"{name}.png")
    if os.path.exists(stale_png):
        os.remove(stale_png)
    print(f"Saved: {name}.xml ({img.width}x{img.height} px at {dp_per_px}dp)")

def make_frame(fill_color, border_color=PALETTE["BARK"], highlight_color=None, sunken=False, disabled=False,
               width=24, height=24):
    """
    Nine-patch frame anatomy (24x24 for buttons and panels, 32x20 for chips):
    - (width-2)x(height-2) body, 2px border
    - 2px Ink shadow at bottom-right (unless disabled or sunken)
    - If sunken, body is shifted 2px down-right
    """
    img = Image.new("RGBA", (width, height), PALETTE["CLEAR"])
    draw = ImageDraw.Draw(img)
    right, bottom = width - 1, height - 1

    if disabled:
        # Body at (0, 0), 2px Cork border, Parchment fill, no shadow
        draw.rectangle([0, 0, right - 2, bottom - 2], fill=border_color)
        draw.rectangle([2, 2, right - 4, bottom - 4], fill=fill_color)
        return img

    if not sunken:
        # Shadow: the last 2 rows and columns, starting 2px in
        draw.rectangle([2, bottom - 1, right, bottom], fill=PALETTE["INK"])
        draw.rectangle([right - 1, 2, right, bottom - 2], fill=PALETTE["INK"])
        # Body at (0, 0)
        draw.rectangle([0, 0, right - 2, bottom - 2], fill=border_color)
        draw.rectangle([2, 2, right - 4, bottom - 4], fill=fill_color)
        if highlight_color:
            # 2px highlight strip along top inner row (inside top inset)
            draw.rectangle([2, 2, right - 4, 3], fill=highlight_color)
    else:
        # Sunken: body moved to (2, 2)
        draw.rectangle([2, 2, right, bottom], fill=border_color)
        draw.rectangle([4, 4, right - 2, bottom - 2], fill=fill_color)

    return img

