def draw_mark(d, ox, oy, scale=1, mono=False):
    """
    The Polaroam mark: a 22x27 polaroid (times scale) with its top-left at (ox, oy).
    mono draws the one-color silhouette: frame and picture in Warm White, photo knocked out.
    """
    def rect(x0, y0, x1, y1, color):
        d.rectangle([ox + x0 * scale, oy + y0 * scale, ox + (x1 + 1) * scale - 1, oy + (y1 + 1) * scale - 1], fill=color)

    white = PALETTE["WHITE"]
    rect(0, 0, 21, 26, white if mono else PALETTE["BARK"])
    rect(1, 1, 20, 25, white)
    rect(3, 3, 18, 18, PALETTE["CLEAR"] if mono else PALETTE["INK"])
    rect(13, 5, 16, 8, white if mono else PALETTE["GOLD"])
    pine = white if mono else PALETTE["PINE"]
    for x0, y0, x1, y1 in [(9, 11, 10, 12), (7, 13, 12, 14), (3, 15, 14, 16), (3, 17, 18, 18)]:
        rect(x0, y0, x1, y1, pine)
    moss = white if mono else PALETTE["MOSS"]
    for x0, y0, x1, y1 in [(13, 15, 14, 16), (11, 17, 16, 18)]:
        rect(x0, y0, x1, y1, moss)

